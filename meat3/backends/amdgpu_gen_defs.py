#!/usr/bin/env python3
"""Developer tool: regenerate amdgpu_metrics_defs.py from the kernel header.

    python3 -m meat3.backends.amdgpu_gen_defs \
        ~/meat3-src/linux/drivers/gpu/drm/amd/include/kgd_pp_interface.h [--verify]

Parses every `struct gpu_metrics_vX_Y` (plus the nested `amdgpu_xcp_metrics*`
structs) from kgd_pp_interface.h, lays them out with the x86-64/arm64 natural
alignment rules the kernel is compiled with (the structs are not __packed), and
writes a table-driven layout description. `--verify` compiles a tiny C program
with gcc and checks every offset/sizeof against the compiler.

Not imported at runtime; the generated module is checked in.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile

CTYPES = {  # C type -> (struct format char, size)
    "uint8_t": ("B", 1), "int8_t": ("b", 1),
    "uint16_t": ("H", 2), "int16_t": ("h", 2),
    "uint32_t": ("I", 4), "int32_t": ("i", 4), "int": ("i", 4),
    "uint64_t": ("Q", 8), "int64_t": ("q", 8),
}

STRUCT_RE = re.compile(r"struct\s+(\w+)\s*\{(.*?)\};", re.S)
FIELD_RE = re.compile(r"^(struct\s+\w+|\w+)\s+(\w+)\s*(?:\[\s*(\w*)\s*\])?$")
WANTED = re.compile(r"^(gpu_metrics_v\d+_\d+|amdgpu_xcp_metrics(_v\d+_\d+)?|metrics_table_header)$")


def strip_comments(s: str) -> str:
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def parse(header_text: str):
    text = strip_comments(header_text)
    consts = {m.group(1): int(m.group(2), 0)
              for m in re.finditer(r"#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\b", text)}
    raw = {}
    for m in STRUCT_RE.finditer(text):
        name, body = m.group(1), m.group(2)
        if not WANTED.match(name):
            continue
        fields = []
        for decl in body.split(";"):
            decl = " ".join(decl.split())
            if not decl:
                continue
            fm = FIELD_RE.match(decl)
            if not fm:
                raise ValueError(f"cannot parse field in {name}: {decl!r}")
            ctype, fname, dim = fm.groups()
            if dim is None:
                count = 1
            elif dim == "":
                count = 0  # flexible array member
            else:
                count = consts[dim] if dim in consts else int(dim, 0)
            fields.append((ctype, fname, count))
        raw[name] = fields

    layouts = {}

    def layout(name):
        if name in layouts:
            return layouts[name]
        off, align, out = 0, 1, []
        for ctype, fname, count in raw[name]:
            if ctype.startswith("struct "):
                sub = ctype.split()[1]
                if sub not in raw:  # e.g. gpu_metrics_attr flexible array (v1_9)
                    out.append((fname, off, "flex:" + sub, count))
                    continue
                ssize, salign, _ = layout(sub)
                off = (off + salign - 1) // salign * salign
                out.append((fname, off, "struct:" + sub, count))
                off += ssize * count
                align = max(align, salign)
            else:
                fmt, size = CTYPES[ctype]
                off = (off + size - 1) // size * size
                out.append((fname, off, fmt, count))
                off += size * max(count, 0)
                align = max(align, size)
        size = (off + align - 1) // align * align
        layouts[name] = (size, align, out)
        return layouts[name]

    for n in raw:
        layout(n)
    return raw, layouts


def parse_enum(header_text: str, enum_name: str, prefix: str) -> list:
    text = strip_comments(header_text)
    m = re.search(r"enum\s+" + enum_name + r"\s*\{(.*?)\};", text, re.S)
    names = []
    for item in m.group(1).split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            raise ValueError("explicit enum values not supported: " + item)
        names.append(item[len(prefix):] if item.startswith(prefix) else item)
    return names


def emit(layouts, src_desc: str, attr_ids=(), attr_units=()) -> str:
    lines = [
        '"""AUTO-GENERATED by amdgpu_gen_defs.py from kgd_pp_interface.h -- do not edit.',
        "",
        f"Source: {src_desc}",
        "Layout: natural alignment (kernel structs are not __packed).",
        "Each field: (name, offset, kind, count); kind is a struct format char, or",
        "'struct:<name>' for nested arrays, or 'flex:<name>' for flexible arrays.",
        '"""',
        "",
        "STRUCTS = {",
    ]
    for name in sorted(layouts):
        size, align, fields = layouts[name]
        lines.append(f"    {name!r}: ({size}, [")
        for f in fields:
            lines.append(f"        {f!r},")
        lines.append("    ]),")
    lines.append("}")
    lines.append("")
    lines.append("# (format_revision, content_revision) -> struct name")
    lines.append("VERSIONS = {")
    for name in sorted(layouts):
        m = re.match(r"gpu_metrics_v(\d+)_(\d+)$", name)
        if m:
            lines.append(f"    ({int(m.group(1))}, {int(m.group(2))}): {name!r},")
    lines.append("}")
    lines.append("")
    lines.append("# enum amdgpu_metrics_attr_id (attribute-encoded tables, gpu_metrics v1_9+)")
    lines.append("ATTR_IDS = " + repr(list(attr_ids)))
    lines.append("# enum amdgpu_metrics_attr_unit")
    lines.append("ATTR_UNITS = " + repr(list(attr_units)))
    return "\n".join(lines) + "\n"


def verify(header_text: str, raw, layouts) -> None:
    text = strip_comments(header_text)
    defines = "\n".join(m.group(0) for m in re.finditer(r"#define\s+(NUM_|MAX_)\w+\s+\d+", text))
    bodies = []
    for m in STRUCT_RE.finditer(text):
        if m.group(1) in raw or m.group(1) == "gpu_metrics_attr":
            bodies.append(m.group(0))
    checks = []
    for name, (size, _a, fields) in layouts.items():
        checks.append(f'chk("{name}", "sizeof", sizeof(struct {name}), {size});')
        for fname, off, kind, count in fields:
            checks.append(f'chk("{name}", "{fname}", offsetof(struct {name}, {fname}), {off});')
    prog = ("#include <stdint.h>\n#include <stddef.h>\n#include <stdio.h>\n" + defines + "\n" +
            "\n".join(bodies) + "\nstatic int bad;\nstatic void chk(const char*s,const char*f,"
            "size_t got,size_t want){if(got!=want){printf(\"MISMATCH %s.%s gcc=%zu ours=%zu\\n\",s,f,got,want);bad=1;}}\n"
            "int main(void){\n" + "\n".join(checks) + "\nprintf(bad?\"FAIL\\n\":\"OK %d checks\\n\", " +
            str(len(checks)) + ");return bad;}\n")
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "v.c")
        with open(c, "w") as fh:
            fh.write(prog)
        exe = os.path.join(d, "v")
        subprocess.run(["gcc", "-O0", "-o", exe, c], check=True)
        r = subprocess.run([exe], capture_output=True, text=True)
        print(r.stdout.strip())
        if r.returncode:
            raise SystemExit(1)


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    hdr = os.path.expanduser(argv[0])
    with open(hdr) as fh:
        text = fh.read()
    raw, layouts = parse(text)
    if "--verify" in argv:
        verify(text, raw, layouts)
    src = os.environ.get("MEAT3_DEFS_SRC_DESC", os.path.basename(hdr))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "amdgpu_metrics_defs.py")
    with open(out, "w") as fh:
        fh.write(emit(layouts, src,
                      parse_enum(text, "amdgpu_metrics_attr_id", "AMDGPU_METRICS_ATTR_ID_")[:-1],
                      parse_enum(text, "amdgpu_metrics_attr_unit", "AMDGPU_METRICS_UNIT_")[:-1]))
    print(f"wrote {out}: {len(layouts)} structs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
